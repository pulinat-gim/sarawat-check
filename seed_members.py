def seed_database():
    default_password_hash = generate_password_hash("123456") # รหัสผ่านเริ่มต้นสำหรับทุกคน
    
    with sqlite3.connect(DB_PATH) as conn:
        cursor = conn.cursor()
        for m in members_data:
            # ตรวจสอบว่ามีรหัสนี้อยู่แล้วหรือยัง เพื่อป้องกันการเพิ่มซ้ำ
            cursor.execute("SELECT id FROM members WHERE student_code = ?", (m["code"],))
            existing = cursor.fetchone()
            
            if not existing:
                cursor.execute("""
                    INSERT INTO members (student_code, full_name, class_room, role, password_hash, is_active)
                    VALUES (?, ?, ?, 'member', ?, 1)
                """, (m["code"], m["name"], m["room"], default_password_hash))
        
        conn.commit()
    print("เพิ่มข้อมูลสมาชิก 39 คนลงฐานข้อมูลสำเร็จแล้ว!")

if __name__ == "__main__":
    seed_database()